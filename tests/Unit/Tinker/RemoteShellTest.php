<?php declare(strict_types=1);

namespace Multiapi\Arco\Tests\Unit\Tinker;

use Multiapi\Arco\Tests\Unit\Commands\FakeConsole;
use Multiapi\Arco\Tinker\RemoteExecution;
use Multiapi\Arco\Tinker\RemoteShell;
use Multiapi\Arco\Tinker\TinkerSession;
use PHPUnit\Framework\TestCase;
use Psy\Configuration;
use Symfony\Component\Console\Output\BufferedOutput;

final class RemoteShellTest extends TestCase
{
    private string $dir;

    protected function setUp(): void
    {
        $this->dir = sys_get_temp_dir() . '/arco-remote-shell-' . bin2hex(random_bytes(4));
        mkdir($this->dir);
    }

    protected function tearDown(): void
    {
        exec('rm -rf ' . escapeshellarg($this->dir));
    }

    /** Runs the shell on $lines (then exit) and returns the console calls. @param list<string> $lines @return list<array{0: string, 1: string, 2: int|string|null, 3: string|null}> */
    private function drive(array $lines, int $replies = 5): array
    {
        $console = new FakeConsole(array_fill(0, $replies, FakeConsole::tinkerReply(['presented' => 'remote'])));
        $config = RemoteShell::configuration(TinkerSessionTest::config(), $this->dir);
        $config->setInteractiveMode(Configuration::INTERACTIVE_MODE_FORCED);
        $config->setColorMode(Configuration::COLOR_MODE_DISABLED);
        $shell = new RemoteShell($config, new RemoteExecution(new TinkerSession($console, TinkerSessionTest::config()), fn () => null));
        $shell->addInput([...$lines, 'exit'], true);

        $shell->run(null, new BufferedOutput());

        return $console->calls;
    }

    public function test_a_plain_statement_makes_exactly_one_invocation(): void
    {
        self::assertSame(['return 1 + 1;'], array_column($this->drive(['1 + 1']), 1));
    }

    public function test_timeit_makes_no_remote_call(): void
    {
        self::assertSame([], $this->drive(['timeit 1+1']));
    }

    public function test_commands_that_evaluate_expressions_make_no_hidden_invocation(): void
    {
        foreach (['doc strlen', 'show strlen', 'dump 1', 'copy 1', 'config set verbosity 1', 'ls -l 1', 'sudo $a = 1', 'trace', 'wtf', 'edit', 'throw-up', 'whereami'] as $line) {
            // Without the command, the line is an ordinary (often invalid) statement: sent at most once, as typed.
            $calls = $this->drive([$line]);
            self::assertLessThanOrEqual(1, count($calls), "\"$line\" sent more than once");
            foreach ($calls as $call) {
                self::assertStringNotContainsString('Psy\\', $call[1], "\"$line\" sent code generated by a PsySH command");
            }
        }
    }

    public function test_only_commands_that_never_evaluate_code_remain(): void
    {
        $config = RemoteShell::configuration(TinkerSessionTest::config(), $this->dir);
        $shell = new RemoteShell($config, new RemoteExecution(new TinkerSession(new FakeConsole(), TinkerSessionTest::config()), fn () => null));
        $shell->boot();

        $names = array_values(array_unique(array_map(fn ($command) => (string) $command->getName(), $shell->all())));
        sort($names);
        self::assertSame([], array_diff($names, RemoteShell::COMMANDS), 'unexpected commands: ' . implode(', ', $names));
        self::assertTrue($shell->has('help'));
        self::assertTrue($shell->has('exit'));
        self::assertFalse($shell->has('timeit'));
        self::assertFalse($shell->has('ls'));
    }

    public function test_the_configuration_keeps_everything_remote_and_apart(): void
    {
        file_put_contents($this->dir . '/.psysh.php', '<?php $GLOBALS["arco_local_psysh_loaded"] = true; return ["defaultIncludes" => ["/tmp/x.php"]];');
        $cwd = (string) getcwd();
        chdir($this->dir);
        try {
            $config = RemoteShell::configuration(TinkerSessionTest::config(), $this->dir);
        } finally {
            chdir($cwd);
        }

        self::assertArrayNotHasKey('arco_local_psysh_loaded', $GLOBALS);
        self::assertSame([], $config->getDefaultIncludes());
        self::assertFalse($config->usePcntl());
        self::assertSame($this->dir . '/arco-shop-staging_history', $config->getHistoryFile());
    }
}
